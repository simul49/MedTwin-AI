class Document(models.Model):
    """Uploaded health document. The file lives outside the public static tree
    and is only served through an authorized view (PRD §10.3)."""

    id = models.CharField(primary_key=True, max_length=36)
    owner = models.ForeignKey(
        "accounts.User", on_delete=models.CASCADE, db_column="owner_id", related_name="uploaded_documents"
    )
    patient = models.ForeignKey(
        "accounts.User", on_delete=models.CASCADE, db_column="patient_id", related_name="documents"
    )
    name = models.CharField(max_length=255)
    mime_type = models.CharField(max_length=120)
    size_bytes = models.PositiveIntegerField(default=0)
    storage_path = models.CharField(max_length=400)
    sha256 = models.CharField(max_length=64, null=True, blank=True)
    category = models.CharField(max_length=40, default="OTHER")
    processing_status = models.CharField(max_length=15, choices=PROCESSING_STATUS, default="UPLOADED")
    processing_error = models.CharField(max_length=255, null=True, blank=True)
    extracted_text = models.TextField(null=True, blank=True)
    page_count = models.PositiveIntegerField(null=True, blank=True)
    uploaded_by = models.ForeignKey(
        "accounts.User",
        on_delete=models.SET_NULL,
        db_column="uploaded_by",
        null=True,
        blank=True,
        related_name="+",
    )
    created_at = models.DateTimeField(default=timezone.now)
    processed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        managed = False
        db_table = "documents"
        ordering = ["-created_at"]


