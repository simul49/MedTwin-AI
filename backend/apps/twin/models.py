"""Digital Twin data: records, observations, allergies, medications,
documents and the health timeline (PRD §9, §10)."""
from django.db import models
from django.utils import timezone

SOURCE_TYPES = [
    ("USER", "Entered by the patient"),
    ("CLINICIAN", "Authored by a clinician"),
    ("EXTRACTED", "Extracted from a document"),
    ("AI_GENERATED", "Generated by AI (draft)"),
    ("DEVICE", "Imported from a device"),
]

VERIFICATION_STATUS = [
    ("UNVERIFIED", "Unverified"),
    ("USER_CONFIRMED", "Confirmed by patient"),
    ("CLINICIAN_CONFIRMED", "Confirmed by clinician"),
    ("EXTRACTED_REVIEWED", "Reviewed extraction"),
]

RECORD_CATEGORIES = [
    ("CONDITION", "Condition"),
    ("ALLERGY", "Allergy"),
    ("MEDICATION", "Medication"),
    ("LAB_RESULT", "Lab result"),
    ("PROCEDURE", "Procedure"),
    ("IMMUNIZATION", "Immunization"),
    ("NOTE", "Note"),
    ("FAMILY_HISTORY", "Family history"),
    ("VITAL", "Vital sign"),
]

PROCESSING_STATUS = [
    ("UPLOADED", "Uploaded"),
    ("PROCESSING", "Processing"),
    ("PROCESSED", "Processed"),
    ("FAILED", "Failed"),
]


class HealthRecord(models.Model):
    id = models.CharField(primary_key=True, max_length=36)
    patient = models.ForeignKey(
        "accounts.User", on_delete=models.CASCADE, db_column="patient_id", related_name="health_records"
    )
    category = models.CharField(max_length=20, choices=RECORD_CATEGORIES)
    title = models.CharField(max_length=200)
    summary = models.TextField(null=True, blank=True)
    payload = models.JSONField(null=True, blank=True)
    source_type = models.CharField(max_length=15, choices=SOURCE_TYPES, default="USER")
    verification_status = models.CharField(max_length=20, choices=VERIFICATION_STATUS, default="UNVERIFIED")
    source_document = models.ForeignKey(
        "twin.Document",
        on_delete=models.SET_NULL,
        db_column="source_document_id",
        null=True,
        blank=True,
        related_name="records",
    )
    author = models.ForeignKey(
        "accounts.User",
        on_delete=models.SET_NULL,
        db_column="author_id",
        null=True,
        blank=True,
        related_name="+",
    )
    recorded_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(default=timezone.now)
    updated_at = models.DateTimeField(default=timezone.now)

    class Meta:
        managed = False
        db_table = "health_records"
        ordering = ["-recorded_at", "-created_at"]

    @property
    def is_ai_generated(self) -> bool:
        return self.source_type == "AI_GENERATED"


class Observation(models.Model):
    id = models.CharField(primary_key=True, max_length=36)
    patient = models.ForeignKey(
        "accounts.User", on_delete=models.CASCADE, db_column="patient_id", related_name="observations"
    )
    code = models.CharField(max_length=40, null=True, blank=True)
    label = models.CharField(max_length=120)
    value_numeric = models.DecimalField(max_digits=12, decimal_places=4, null=True, blank=True)
    value_text = models.CharField(max_length=255, null=True, blank=True)
    unit = models.CharField(max_length=30, null=True, blank=True)
    reference_range = models.CharField(max_length=60, null=True, blank=True)
    flag = models.CharField(max_length=10, default="UNKNOWN")
    observed_at = models.DateTimeField()
    source_type = models.CharField(max_length=15, choices=SOURCE_TYPES, default="USER")
    source_document_id = models.CharField(max_length=36, null=True, blank=True)
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        managed = False
        db_table = "observations"
        ordering = ["-observed_at"]

    @property
    def display_value(self) -> str:
        """Human-readable value without DECIMAL artefacts (7.1000 -> 7.1)."""
        if self.value_numeric is not None:
            value = float(self.value_numeric)
            rendered = str(int(value)) if value.is_integer() else f"{value:g}"
            return f"{rendered} {self.unit or ''}".strip()
        return self.value_text or "—"


